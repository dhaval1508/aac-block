"use server";

import { prisma } from "@/lib/prisma";
import { getSession } from "@/lib/session";
import {
  generateSecureQrToken,
  getOrderQrUrl,
  generateQrDataUrl,
  generateQrSvg,
  formatOrderQrWhatsAppText,
} from "@/lib/qr";
import { QrStatus } from "@prisma/client";
import { revalidatePath } from "next/cache";

/**
 * Verifies that the current caller has ADMIN privileges.
 */
async function requireAdminSession() {
  const session = await getSession();
  if (!session || session.role !== "ADMIN") {
    throw new Error("Unauthorized: Only Super Admin and authorized Administrators can manage Order QR codes.");
  }
  return session;
}

/**
 * Ensures an Order has an active QR code. If none exists, generates one.
 */
export async function getOrCreateOrderQrAction(orderId: string) {
  const session = await requireAdminSession();

  let qr = await prisma.orderQrCode.findUnique({
    where: { orderId },
    include: {
      order: {
        select: {
          id: true,
          orderNo: true,
          status: true,
          totalCbm: true,
          quantity: true,
          deliveryAddress: true,
          customer: { select: { id: true, name: true, mobile: true, email: true, companyName: true } },
        },
      },
    },
  });

  if (!qr) {
    const token = generateSecureQrToken();
    qr = await prisma.orderQrCode.create({
      data: {
        orderId,
        token,
        status: QrStatus.ACTIVE,
        createdById: session.id,
        createdByName: session.name,
      },
      include: {
        order: {
          select: {
            id: true,
            orderNo: true,
            status: true,
            totalCbm: true,
            quantity: true,
            deliveryAddress: true,
            customer: { select: { id: true, name: true, mobile: true, email: true, companyName: true } },
          },
        },
      },
    });

    // Log event in order history
    await prisma.orderEvent.create({
      data: {
        orderId,
        status: qr.order.status,
        title: "Order QR Code Generated",
        note: `Digital Order QR Code generated by Admin (${session.name})`,
        createdById: session.id,
      },
    });
  }

  const qrUrl = getOrderQrUrl(qr.token);
  const [dataUrl, svg] = await Promise.all([
    generateQrDataUrl(qrUrl),
    generateQrSvg(qrUrl),
  ]);

  const whatsappText = formatOrderQrWhatsAppText({
    orderNo: qr.order.orderNo,
    customerName: qr.order.customer?.name || "Customer",
    totalCbm: qr.order.totalCbm ? Number(qr.order.totalCbm) : null,
    totalBlocks: qr.order.quantity,
    status: qr.order.status,
    deliverySite: qr.order.deliveryAddress,
    qrUrl,
  });

  return {
    qr: {
      id: qr.id,
      orderId: qr.orderId,
      token: qr.token,
      status: qr.status,
      accessPolicy: qr.accessPolicy,
      createdAt: qr.createdAt.toISOString(),
      updatedAt: qr.updatedAt.toISOString(),
      expiresAt: qr.expiresAt?.toISOString() || null,
      revokedAt: qr.revokedAt?.toISOString() || null,
      revokedReason: qr.revokedReason,
      createdByName: qr.createdByName,
    },
    qrUrl,
    dataUrl,
    svg,
    whatsappText,
    customer: qr.order.customer,
    orderNo: qr.order.orderNo,
  };
}

/**
 * Loads detailed QR information, scan logs, and sharing logs for an order.
 */
export async function getOrderQrDetailsAction(orderId: string) {
  await requireAdminSession();

  const qr = await prisma.orderQrCode.findUnique({
    where: { orderId },
    include: {
      order: {
        select: {
          id: true,
          orderNo: true,
          status: true,
          totalCbm: true,
          quantity: true,
          deliveryAddress: true,
          customer: { select: { id: true, name: true, mobile: true, email: true, companyName: true } },
        },
      },
      shareLogs: {
        orderBy: { createdAt: "desc" },
        take: 20,
      },
      scanLogs: {
        orderBy: { scannedAt: "desc" },
        take: 20,
      },
      _count: {
        select: {
          scanLogs: true,
          shareLogs: true,
        },
      },
    },
  });

  if (!qr) return null;

  const qrUrl = getOrderQrUrl(qr.token);
  const [dataUrl, svg] = await Promise.all([
    generateQrDataUrl(qrUrl),
    generateQrSvg(qrUrl),
  ]);

  const whatsappText = formatOrderQrWhatsAppText({
    orderNo: qr.order.orderNo,
    customerName: qr.order.customer?.name || "Customer",
    totalCbm: qr.order.totalCbm ? Number(qr.order.totalCbm) : null,
    totalBlocks: qr.order.quantity,
    status: qr.order.status,
    deliverySite: qr.order.deliveryAddress,
    qrUrl,
  });

  return {
    qr: {
      id: qr.id,
      orderId: qr.orderId,
      token: qr.token,
      status: qr.status,
      accessPolicy: qr.accessPolicy,
      createdAt: qr.createdAt.toISOString(),
      updatedAt: qr.updatedAt.toISOString(),
      expiresAt: qr.expiresAt?.toISOString() || null,
      revokedAt: qr.revokedAt?.toISOString() || null,
      revokedReason: qr.revokedReason,
      createdByName: qr.createdByName,
    },
    qrUrl,
    dataUrl,
    svg,
    whatsappText,
    customer: qr.order.customer,
    orderNo: qr.order.orderNo,
    totalScans: qr._count.scanLogs,
    totalShares: qr._count.shareLogs,
    shareLogs: qr.shareLogs.map((l) => ({
      id: l.id,
      channel: l.channel,
      recipient: l.recipient,
      sentByName: l.sentByName,
      status: l.status,
      createdAt: l.createdAt.toISOString(),
    })),
    scanLogs: qr.scanLogs.map((s) => ({
      id: s.id,
      scannedAt: s.scannedAt.toISOString(),
      result: s.result,
      userAgent: s.userAgent,
    })),
  };
}

/**
 * Regenerates an Order QR code with a new secure token, revoking the previous one.
 */
export async function regenerateOrderQrAction(orderId: string, reason?: string) {
  const session = await requireAdminSession();

  const newToken = generateSecureQrToken();
  const revocationReason = reason?.trim() || "Regenerated with new secure token by Super Admin";

  const result = await prisma.$transaction(async (tx) => {
    // 1. Mark existing QR as revoked if exists
    const existing = await tx.orderQrCode.findUnique({ where: { orderId } });
    if (existing) {
      await tx.orderQrCode.update({
        where: { id: existing.id },
        data: {
          token: newToken,
          status: QrStatus.ACTIVE,
          revokedAt: null,
          revokedById: null,
          revokedReason: null,
          createdById: session.id,
          createdByName: session.name,
          updatedAt: new Date(),
        },
      });
    } else {
      await tx.orderQrCode.create({
        data: {
          orderId,
          token: newToken,
          status: QrStatus.ACTIVE,
          createdById: session.id,
          createdByName: session.name,
        },
      });
    }

    const order = await tx.order.findUnique({
      where: { id: orderId },
      select: { orderNo: true, status: true },
    });

    await tx.orderEvent.create({
      data: {
        orderId,
        status: order?.status || "CONFIRMED",
        title: "Order QR Code Regenerated",
        note: `QR Code regenerated by Admin (${session.name}). Reason: ${revocationReason}`,
        createdById: session.id,
      },
    });

    return { newToken, orderNo: order?.orderNo };
  });

  revalidatePath(`/admin/orders/${orderId}`);
  revalidatePath("/admin/orders/qr-center");

  return { success: true, token: result.newToken };
}

/**
 * Revokes an Order QR code.
 */
export async function revokeOrderQrAction(orderId: string, reason: string) {
  const session = await requireAdminSession();

  const qr = await prisma.orderQrCode.findUnique({ where: { orderId } });
  if (!qr) throw new Error("QR Code not found for this order.");

  const cleanReason = reason?.trim() || "Revoked by Super Admin";

  await prisma.$transaction(async (tx) => {
    await tx.orderQrCode.update({
      where: { id: qr.id },
      data: {
        status: QrStatus.REVOKED,
        revokedAt: new Date(),
        revokedById: session.id,
        revokedReason: cleanReason,
      },
    });

    const order = await tx.order.findUnique({
      where: { id: orderId },
      select: { status: true },
    });

    await tx.orderEvent.create({
      data: {
        orderId,
        status: order?.status || "CONFIRMED",
        title: "Order QR Code Revoked",
        note: `QR code revoked by Admin (${session.name}). Reason: ${cleanReason}`,
        createdById: session.id,
      },
    });
  });

  revalidatePath(`/admin/orders/${orderId}`);
  revalidatePath("/admin/orders/qr-center");

  return { success: true };
}


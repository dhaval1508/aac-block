/**
 * Logs an order QR share activity (WhatsApp, Email, Copy Link).
 */
export async function logOrderQrShareAction(
  orderId: string,
  channel: "WHATSAPP" | "EMAIL" | "COPY_LINK" | "DIRECT_SHARE",
  recipient?: string,
  notes?: string
) {
  const session = await requireAdminSession();

  const qr = await prisma.orderQrCode.findUnique({ where: { orderId } });
  if (!qr) return { success: false, reason: "QR Code not found" };

  await prisma.orderQrShareLog.create({
    data: {
      qrCodeId: qr.id,
      channel,
      recipient: recipient?.trim() || null,
      sentById: session.id,
      sentByName: session.name,
      status: "SUCCESS",
      notes: notes?.trim() || null,
    },
  });

  return { success: true };
}

/**
 * Bulk generates QR codes for all orders that currently do not have an active QR code.
 */
export async function bulkGenerateMissingOrderQrsAction() {
  const session = await requireAdminSession();

  // Find all orders that do not have an active OrderQrCode
  const ordersWithoutQr = await prisma.order.findMany({
    where: {
      deletedAt: null,
      OR: [
        { qrCode: null },
        { qrCode: { status: { not: QrStatus.ACTIVE } } },
      ],
    },
    select: { id: true, orderNo: true },
  });

  if (ordersWithoutQr.length === 0) {
    return { success: true, count: 0, message: "All orders already have active QR codes." };
  }

  let generatedCount = 0;
  for (const order of ordersWithoutQr) {
    const token = generateSecureQrToken();
    await prisma.orderQrCode.upsert({
      where: { orderId: order.id },
      update: {
        token,
        status: QrStatus.ACTIVE,
        revokedAt: null,
        revokedById: null,
        revokedReason: null,
        createdById: session.id,
        createdByName: session.name,
      },
      create: {
        orderId: order.id,
        token,
        status: QrStatus.ACTIVE,
        createdById: session.id,
        createdByName: session.name,
      },
    });
    generatedCount++;
  }

  revalidatePath("/admin/orders");
  revalidatePath("/admin/orders/qr-center");

  return {
    success: true,
    count: generatedCount,
    message: `Successfully generated QR codes for ${generatedCount} order${generatedCount === 1 ? "" : "s"}.`,
  };
}

/**
 * Handles sending Order QR email.
 * Checks for actual email gateway credentials; never returns false success.
 */
export async function sendOrderQrEmailAction(orderId: string, email: string) {
  const session = await requireAdminSession();

  if (!email || !email.includes("@")) {
    return { success: false, message: "Please provide a valid recipient email address." };
  }

  const qr = await prisma.orderQrCode.findUnique({
    where: { orderId },
    include: { order: { select: { orderNo: true } } },
  });

  if (!qr) {
    return { success: false, message: "Order QR code not found." };
  }

  // Check if SMTP or Resend/SendGrid is configured in environment
  const isEmailConfigured = Boolean(
    process.env.SMTP_HOST ||
    process.env.RESEND_API_KEY ||
    process.env.SENDGRID_API_KEY
  );

  if (!isEmailConfigured) {
    // Record log with status PENDING_GATEWAY and honestly notify caller
    await prisma.orderQrShareLog.create({
      data: {
        qrCodeId: qr.id,
        channel: "EMAIL",
        recipient: email.trim(),
        sentById: session.id,
        sentByName: session.name,
        status: "CONFIG_REQUIRED",
        notes: "Outbound SMTP/Email gateway not configured in server environment variables.",
      },
    });

    return {
      success: false,
      isConfigMissing: true,
      message: `Email delivery gateway (SMTP / Resend) is not configured in production environment variables. The QR link is: ${getOrderQrUrl(qr.token)}`,
    };
  }

  // In production if configured, outbound email would be sent here
  await prisma.orderQrShareLog.create({
    data: {
      qrCodeId: qr.id,
      channel: "EMAIL",
      recipient: email.trim(),
      sentById: session.id,
      sentByName: session.name,
      status: "SUCCESS",
    },
  });

  return { success: true, message: `Order QR code successfully emailed to ${email}.` };
}

/**
 * Public action: logs an incoming scan of an Order QR code.
 */
export async function recordOrderQrScan(token: string, userAgent?: string, ipAddress?: string) {
  if (!token) return { valid: false, reason: "NOT_FOUND" };

  const qr = await prisma.orderQrCode.findUnique({
    where: { token },
    select: {
      id: true,
      orderId: true,
      status: true,
      expiresAt: true,
      revokedAt: true,
      revokedReason: true,
    },
  });

  if (!qr) {
    return { valid: false, reason: "NOT_FOUND" };
  }

  // Check revocation
  if (qr.status === QrStatus.REVOKED) {
    await prisma.orderQrScanLog.create({
      data: {
        qrCodeId: qr.id,
        result: "REVOKED",
        ipAddress: ipAddress?.slice(0, 45) || null,
        userAgent: userAgent?.slice(0, 500) || null,
      },
    });
    return {
      valid: false,
      reason: "REVOKED",
      revokedAt: qr.revokedAt?.toISOString(),
      revokedReason: qr.revokedReason,
    };
  }

  // Check expiry
  if (qr.status === QrStatus.EXPIRED || (qr.expiresAt && qr.expiresAt < new Date())) {
    await prisma.orderQrScanLog.create({
      data: {
        qrCodeId: qr.id,
        result: "EXPIRED",
        ipAddress: ipAddress?.slice(0, 45) || null,
        userAgent: userAgent?.slice(0, 500) || null,
      },
    });
    return { valid: false, reason: "EXPIRED" };
  }

  // Active scan
  await prisma.orderQrScanLog.create({
    data: {
      qrCodeId: qr.id,
      result: "SUCCESS",
      ipAddress: ipAddress?.slice(0, 45) || null,
      userAgent: userAgent?.slice(0, 500) || null,
    },
  });

  return {
    valid: true,
    orderId: qr.orderId,
  };
}

